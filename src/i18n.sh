# shellcheck shell=bash
# =============================================================================
# i18n.sh - internationalization (message catalogs + language selection)
# =============================================================================
# LSSHM source strings are written in English (the msgid). Translations are
# stored in per-language associative arrays keyed by the English msgid.
# A missing translation falls back to English, so the tool is always usable
# even with an incomplete catalog.
#
# Adding a language:
#   1. Add its code to LSSHM_LANGS and a native name in lsshm_lang_native_name.
#   2. Declare LSSHM_MSG_<code> and populate it below (mirror the fr catalog).
#   3. Handle it in lsshm_t and lsshm_detect_lang.
# This module must be sourced (or concatenated) right after common.sh.

# Supported language codes (space separated). English is the built-in default.
LSSHM_LANGS="en fr es"
LSSHM_LANG="${LSSHM_LANG:-en}"

# Global catalogs (must use -g: i18n.sh is sourced from functions in tests/build).
declare -gA LSSHM_MSG_fr
declare -gA LSSHM_MSG_es

# -----------------------------------------------------------------------------
# Lookup helpers
# -----------------------------------------------------------------------------
# lsshm_t MSGID -> prints the translated string (no newline). English falls
# back to the msgid itself, as does any missing translation.
lsshm_t() {
    local msgid="${1-}" out="" nounset_was=0
    # Bash + set -u treats missing associative-array keys as unbound variables.
    # Disable nounset only for the catalog lookup.
    case "${LSSHM_LANG-}" in
        fr|es)
            [[ $- == *u* ]] && nounset_was=1
            set +u
            if [ "${LSSHM_LANG}" = "fr" ]; then
                out="${LSSHM_MSG_fr[$msgid]}"
            else
                out="${LSSHM_MSG_es[$msgid]}"
            fi
            [ "$nounset_was" = 1 ] && set -u
            ;;
    esac
    if [ -n "${out}" ]; then
        printf '%s' "$out"
    else
        printf '%s' "$msgid"
    fi
}

# lsshm_tf MSGID [ARGS...] -> printf the translated format string with ARGS.
lsshm_tf() {
    local fmt; fmt="$(lsshm_t "$1")"; shift
    # shellcheck disable=SC2059
    printf "$fmt" "$@"
}

# lsshm_out MSGID [ARGS...] -> like lsshm_tf but appends a newline (stdout).
lsshm_out() {
    local fmt; fmt="$(lsshm_t "$1")"; shift
    # shellcheck disable=SC2059
    printf "$fmt\n" "$@"
}

# -----------------------------------------------------------------------------
# Language codes and names
# -----------------------------------------------------------------------------
lsshm_lang_is_supported() {
    case " $LSSHM_LANGS " in
        *" $1 "*) return 0 ;;
        *) return 1 ;;
    esac
}

lsshm_lang_native_name() {
    case "$1" in
        en) printf 'English' ;;
        fr) printf 'Français' ;;
        es) printf 'Español' ;;
        *)  printf '%s' "$1" ;;
    esac
}

# Detect the preferred language from the environment locale.
lsshm_detect_lang() {
    local l="${LC_ALL:-${LC_MESSAGES:-${LANG:-}}}"
    l="${l%%.*}"       # drop encoding (fr_FR.UTF-8 -> fr_FR)
    l="${l%%@*}"       # drop modifier
    l="${l%%_*}"       # drop territory (fr_FR -> fr)
    l="$(printf '%s' "$l" | tr '[:upper:]' '[:lower:]')"
    case "$l" in
        fr) printf 'fr' ;;
        es) printf 'es' ;;
        en) printf 'en' ;;
        *)  printf 'en' ;;
    esac
}

# Resolve the active language: explicit override > config > locale detection.
lsshm_i18n_init() {
    local want=""
    if [ -n "${LSSHM_LANG_OVERRIDE:-}" ]; then
        want="$LSSHM_LANG_OVERRIDE"
    elif [ -n "${LSSHM_CFG_LANG:-}" ]; then
        want="$LSSHM_CFG_LANG"
    else
        want="$(lsshm_detect_lang)"
    fi
    if lsshm_lang_is_supported "$want"; then
        LSSHM_LANG="$want"
    else
        LSSHM_LANG="en"
    fi
    export LSSHM_LANG
}

# True when the user has never chosen a language (no value stored in config).
lsshm_i18n_configured() {
    [ -n "${LSSHM_CFG_LANG:-}" ]
}

# Interactive language picker. Preselects the detected system language.
# Persists the choice to the configuration file when possible.
lsshm_i18n_choose() {
    local detected def i=0 code choice
    detected="$(lsshm_detect_lang)"

    printf '\n' >&2
    printf 'Language / Langue / Idioma:\n' >&2
    local -a codes=()
    for code in $LSSHM_LANGS; do
        i=$((i + 1))
        codes+=("$code")
        printf '  %d. %s\n' "$i" "$(lsshm_lang_native_name "$code")" >&2
        [ "$code" = "$detected" ] && def="$i"
    done
    def="${def:-1}"

    # || true: a failed prompt under set -e must not abort LSSHM.
    choice="$(lsshm_prompt "Choice / Choix / Elección" "$def" || true)"
    [ -n "$choice" ] || choice="$def"

    local picked=""
    if [[ "$choice" =~ ^[0-9]+$ ]] && [ "$choice" -ge 1 ] && [ "$choice" -le "${#codes[@]}" ]; then
        picked="${codes[$((choice - 1))]}"
    elif lsshm_lang_is_supported "$choice"; then
        picked="$choice"
    else
        picked="$detected"
    fi

    LSSHM_LANG="$picked"
    export LSSHM_LANG
    LSSHM_CFG_LANG="$picked"
    lsshm_config_set language "$picked" 2>/dev/null || true
    lsshm_out 'Language set to: %s' "$(lsshm_lang_native_name "$picked")"
}

